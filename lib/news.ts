export function formatNewsDate(publishedAt: string): string {
  const formatted = new Intl.DateTimeFormat("ru-RU", {
    month: "long",
    year: "numeric",
  }).format(new Date(publishedAt));

  return formatted.charAt(0).toUpperCase() + formatted.slice(1);
}

